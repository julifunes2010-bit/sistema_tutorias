create table if not exists public.tutorias (
  id bigint generated by default as identity primary key,
  materia text not null check (length(btrim(materia)) > 0),
  curso text not null check (length(btrim(curso)) > 0),
  dia text not null check (length(btrim(dia)) > 0),
  horario text not null check (length(btrim(horario)) > 0)
);

alter table public.tutorias enable row level security;

revoke all on public.tutorias from anon;
revoke all on sequence public.tutorias_id_seq from anon;
grant usage on schema public to authenticated;
grant select, insert, update on public.tutorias to authenticated;
grant usage, select on sequence public.tutorias_id_seq to authenticated;

drop policy if exists "Usuarios autenticados consultan tutorias" on public.tutorias;
drop policy if exists "Usuarios autenticados agregan tutorias" on public.tutorias;
drop policy if exists "Usuarios autenticados editan tutorias" on public.tutorias;

create policy "Usuarios autenticados consultan tutorias"
  on public.tutorias for select to authenticated
  using (true);

create policy "Usuarios autenticados agregan tutorias"
  on public.tutorias for insert to authenticated
  with check (true);

create policy "Usuarios autenticados editan tutorias"
  on public.tutorias for update to authenticated
  using (true)
  with check (true);